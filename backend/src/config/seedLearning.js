async function seedLearningData() {
  const moduleOps = INITIAL_LEARNING_MODULES.map((mod) => ({
    updateOne: {
      filter: { slug: mod.slug },
      update: { $setOnInsert: mod },
      upsert: true,
    },
  }));

  const schemeOps = INITIAL_GOV_SCHEMES.map((scheme) => ({
    updateOne: {
      filter: { schemeId: scheme.schemeId },
      update: { $setOnInsert: scheme },
      upsert: true,
    },
  }));

  const [moduleResult, schemeResult] = await Promise.all([
    LearningModule.bulkWrite(moduleOps),
    GovScheme.bulkWrite(schemeOps),
  ]);

  return {
    seededModules: moduleResult.upsertedCount,
    seededSchemes: schemeResult.upsertedCount,
  };
}

